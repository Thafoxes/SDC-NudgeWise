/** Lightweight A4 exporter. shortcut: built-in fonts support ASCII only; use an embedded Unicode font for multilingual documents. */
import type { Business, Customer, PurchaseOrderDetails, PurchaseOrderItem } from '@/types';
import { purchaseOrderLineTotal } from './purchaseOrder';
export interface DocumentSection { heading:string; lines:string[]; items?:PurchaseOrderItem[] }
const ascii=(value:unknown)=>String(value??'').replace(/\s/g,' ').replace(/[^\x20-\x7e]/g,'?');
const esc=(value:string)=>ascii(value).replace(/\\/g,'\\\\').replace(/\(/g,'\\(').replace(/\)/g,'\\)');
const shown=(value:string|null|undefined)=>value?.trim()||'-';
function wrap(line:string,max=84):string[]{
 const chunks:string[]=[];let rest=ascii(line);
 while(rest.length>max){let idx=rest.lastIndexOf(' ',max);if(idx<max/2)idx=max;chunks.push(rest.slice(0,idx));rest=rest.slice(idx).trimStart();}
 chunks.push(rest);return chunks;
}
export function documentContactSections(business:Business|undefined,customer:Customer|undefined,details?:PurchaseOrderDetails):DocumentSection[]{
 return [{heading:'Supplier / seller',lines:[`Name: ${shown(business?.display_name||business?.name||details?.supplier_name)}`,
  `Address: ${shown(business?business.address:details?.supplier_address)}`,`Phone: ${shown(business?business.phone:details?.supplier_phone)}`,`Email: ${shown(business?business.email:details?.supplier_email)}`]},
 {heading:'Buyer / customer',lines:[`Name: ${shown(customer?.name||details?.buyer_name)}`,`Address: ${shown(customer?.address||details?.buyer_address)}`,
  `Phone: ${shown(customer?.phone||details?.buyer_phone)}`,`Email: ${shown(customer?.email||details?.buyer_email)}`]}];
}
export function createDocumentPdf(title:string,sections:DocumentSection[]):Uint8Array {
 const pages:string[][]=[[]];let y=795;
 const command=(value:string)=>pages[pages.length-1].push(value);
 const nextPage=()=>{pages.push([]);y=795;};
 const space=(height:number)=>{if(y-height<48)nextPage();};
 const text=(value:string,x:number,baseline:number,size=10,font='F1')=>command(`BT /${font} ${size} Tf ${x} ${baseline} Td (${esc(value)}) Tj ET`);
 const line=(value:string,size=10,font='F1')=>{for(const part of wrap(value,Math.floor(511/size))){space(16);text(part,42,y,size,font);y-=16;}};
 line(title,17,'F2');line('Generated by NudgeWise for seller review',9);y-=10;
 for(const section of sections){
  space(50);line(section.heading,12,'F2');
  for(const value of section.lines)line(value);
  if(section.items){
   const widths=[26,180,48,82,82,93];
   const row=(cells:string[],header=false)=>{
    const wrapped=cells.map((cell,i)=>wrap(cell,Math.floor((widths[i]-10)/5.4)));
    const height=Math.max(...wrapped.map(c=>c.length))*12+12;
    let x=42;
    if(header)command(`0.93 g 42 ${y-height} 511 ${height} re f 0 g`);
    for(let i=0;i<widths.length;i++){
     command(`0.75 G 0.5 w ${x} ${y-height} ${widths[i]} ${height} re S 0 G`);
     wrapped[i].forEach((value,j)=>text(value,x+5,y-14-j*12,9,'F3'));
     x+=widths[i];
    }
    y-=height;return height;
   };
   const header=()=>row(['#','Item / code','Qty','Unit price','Discount','Line total'],true);
   space(70);header();
   if(!section.items.length){space(24);row(['-','No items','-','-','-','-']);}
   section.items.forEach((item,index)=>{
    const money=(value:number|null)=>value===null?'-':value.toFixed(2);
    const cells=[String(index+1),`${item.name}${item.code?' / '+item.code:''}`,item.quantity===null?'-':String(item.quantity),money(item.unit_price),money(item.discount),money(purchaseOrderLineTotal(item))];
    const height=Math.max(...cells.map((cell,i)=>wrap(cell,Math.floor((widths[i]-10)/5.4)).length))*12+12;
    if(y-height<48){nextPage();header();}
    row(cells);
   });
   y-=16;
  }
  y-=10;
 }
 line('Business document: verify all terms and applicable regulatory requirements before use.',8);
 const objects:string[]=['','<< /Type /Catalog /Pages 2 0 R >>','','<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>','<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>'];
 const references:number[]=[];const encoder=new TextEncoder();
 pages.forEach((commands,page)=>{
  const pageId=objects.length;const streamId=pageId+1;
  commands.push(`BT /F1 8 Tf 42 28 Td (Page ${page+1} of ${pages.length}) Tj ET`);
  const stream=commands.join('\n');
  objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents ${streamId} 0 R >>`);
  objects.push(`<< /Length ${encoder.encode(stream).length} >>\nstream\n${stream}\nendstream`);references.push(pageId);
 });
 objects[2]=`<< /Type /Pages /Kids [${references.map(i=>`${i} 0 R`).join(' ')}] /Count ${references.length} >>`;
 let src='%PDF-1.4\n';const offsets=[0];
 for(let i=1;i<objects.length;i++){offsets.push(encoder.encode(src).length);src+=`${i} 0 obj\n${objects[i]}\nendobj\n`;}
 const start=encoder.encode(src).length;src+=`xref\n0 ${objects.length}\n0000000000 65535 f \n`;
 for(let i=1;i<objects.length;i++)src+=`${String(offsets[i]).padStart(10,'0')} 00000 n \n`;
 src+=`trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${start}\n%%EOF`;
 return encoder.encode(src);
}
export function downloadDocumentPdf(filename:string,title:string,sections:DocumentSection[]){
 const blob=new Blob([createDocumentPdf(title,sections)],{type:'application/pdf'});
 const url=URL.createObjectURL(blob);const a=document.createElement('a');a.href=url;a.download=filename.replace(/[^a-z0-9_.-]/gi,'_');document.body.append(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),1000);
}

export function viewDocumentPdf(title:string,sections:DocumentSection[]){
 const blob=new Blob([createDocumentPdf(title,sections)],{type:'application/pdf'});
 const url=URL.createObjectURL(blob);window.open(url,'_blank','noopener,noreferrer');
 setTimeout(()=>URL.revokeObjectURL(url),60000);
}
